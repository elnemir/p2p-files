import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { createDraft } from "./transfers";
import { contractObserver } from "./contracts";
import { evidencePath } from "./evidence";

test("WebDAV credential UI uploads into a draft and revokes access", async ({ page, request }) => {
  const contract = await contractObserver(); await contract.observe(page);
  await page.goto("/");
  await page.getByLabel("Email", { exact: true }).fill(process.env.FILEX_E2E_EMAIL!);
  await page.getByLabel("Пароль", { exact: true }).fill(process.env.FILEX_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Войти", exact: true }).click();
  await expect(page.getByRole("button", { name: "Новая передача", exact: true })).toBeVisible();
  await createDraft(page, "WebDAV · папка из файлового менеджера");
  await page.getByText("Загрузка через WebDAV", { exact: true }).click();
  const client = page.getByLabel("Ваш файловый менеджер", { exact: true });
  await expect(page.getByText("Finder → Переход", { exact: false })).toBeVisible();
  await client.selectOption("windows");
  await expect(page.getByText("Фактическая проверка Windows ожидает", { exact: false })).toBeVisible();
  await client.selectOption("linux");
  await expect(page.getByText("GNOME Files → Другие места", { exact: false })).toBeVisible();
  await client.selectOption("macos");
  await page.getByLabel("Пароль аккаунта для выдачи доступа", { exact: true }).fill(process.env.FILEX_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Создать доступ WebDAV", exact: true }).click();
  const field = page.getByLabel("Адрес WebDAV", { exact: true });
  await expect(field).toBeVisible();
  const address = await field.inputValue();
  const password = await page.getByLabel("Пароль подключения WebDAV", { exact: true }).inputValue();
  expect(await page.getByLabel("Имя пользователя WebDAV", { exact: true }).inputValue()).toBe("filex");
  const headers = { Authorization: `Basic ${Buffer.from(`filex:${password}`).toString("base64")}` };
  expect((await request.fetch(address + "documents/", { method: "MKCOL", headers })).status()).toBe(201);
  const payload = Buffer.from("Загрузка через WebDAV\n");
  expect((await request.put(address + "documents/contract.txt", { headers, data: payload })).status()).toBe(201);
  expect((await request.get(address + "documents/contract.txt", { headers })).status()).toBe(200);
  expect((await request.put(address + "documents/contract.txt", { headers, data: payload })).status()).toBe(204);
  const listing = await request.fetch(address + "documents/", { method: "PROPFIND", headers: { ...headers, Depth: "1" } });
  expect(listing.status()).toBe(207); expect(await listing.text()).toContain("contract.txt");
  await page.getByRole("button", { name: "Обновить файлы после WebDAV", exact: true }).click();
  await expect(page.getByText("documents/contract.txt", { exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Проверить перед публикацией", exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  const a11y = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa", "wcag22aa"]).analyze();
  expect(a11y.violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  // Mask generated credentials in evidence even though they belong to a disposable fixture.
  await page.screenshot({ path: evidencePath("webdav-mobile.png"), fullPage: true, mask: [page.getByLabel("Пароль подключения WebDAV", { exact: true })] });
  await page.getByRole("button", { name: "Отозвать доступ WebDAV", exact: true }).click();
  await expect(page.getByRole("button", { name: "Создать доступ WebDAV", exact: true })).toBeVisible();
  expect((await request.fetch(address, { method: "PROPFIND", headers: { ...headers, Depth: "0" } })).status()).toBe(401);
  const result = await contract.finish(); expect(result.failures).toEqual([]);
});
